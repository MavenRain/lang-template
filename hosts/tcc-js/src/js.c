static int emit(Js *o, uint32_t depth, const Core *c);

/* The arguments are evaluated left to right before the call, as in eval.c. */
static int emit_op(Js *o, uint32_t depth, const Core *c) {
  const char *name = NULL;
  Shape shape = op_shape(c->op, &name);
  uint32_t i;
  int ok = 0;
  switch (shape) {
  case JS_CONST:
    return put(o, name);
  case JS_CALL:
    ok = put(o, name) && put(o, "(");
    break;
  case JS_LEAD:
    ok = put(o, name) && put(o, "(") && put_u64(o, c->op == OP_PROJ ? c->field : c->inst);
    break;
  }
  for (i = 0; ok && i < c->argc; i++)
    ok = ((shape == JS_CALL && i == 0) || put(o, ", ")) && emit(o, depth, c->args[i]);
  return ok && put(o, ")");
}

/* DEPTH is the number of binders around C. */
static int emit(Js *o, uint32_t depth, const Core *c) {
  switch (c->kind) {
  case CORE_VAR:
    if (c->index >= depth)
      return internal(o, "a free variable");
    return put(o, "v") && put_u64(o, depth - 1u - c->index);
  case CORE_GLOBAL:
    return put(o, "g") && put_u64(o, c->index) && put(o, "()");
  case CORE_NAT:
    return put_u64(o, c->nat) && put(o, "n");
  case CORE_STR:
    return put_js_string(o, c->name, (size_t)c->nat);
  case CORE_TRAP:
    return put(o, "TRAP");
  case CORE_UNIV:
  case CORE_PI:
  case CORE_SIGMA:
    return put(o, "null");
  case CORE_LAM:
    return put(o, "((v") && put_u64(o, depth) && put(o, ") => ") && emit(o, depth + 1u, c->b) && put(o, ")");
  case CORE_APP:
    return put(o, "app(") && emit(o, depth, c->a) && put(o, ", ") && emit(o, depth, c->b) && put(o, ")");
  case CORE_OP:
    return emit_op(o, depth, c);
  }
  return internal(o, "an unknown core term");
}

static int emit_runtime(Js *o) {
  size_t i;
  int ok = 1;
  for (i = 0; ok && i < sizeof RUNTIME / sizeof RUNTIME[0]; i++)
    ok = put(o, RUNTIME[i]) && put(o, "\n");
  return ok;
}

/* 1 when each constructor of F has no field (JSON writes the name). */
static int all_constants(const Machine *m, const FamilyInfo *f) {
  uint32_t i;
  for (i = 0; i < f->ctor_count; i++)
    if (m->ctors[f->first_ctor + i].field_count != 0)
      return 0;
  return 1;
}

static int emit_ctor_row(Js *o, const CtorInfo *ci) {
  uint32_t j;
  int ok = put(o, "  { name: ") && put_name(o, ci->name) && put(o, ", family: ") && put_u64(o, ci->family)
    && put(o, ", params: ") && put_u64(o, o->m->families[ci->family].param_count) && put(o, ", fields: [");
  for (j = 0; ok && j < ci->field_count; j++)
    ok = (j == 0 || put(o, ", ")) && put_name(o, ci->fields[j].name);
  ok = ok && put(o, "], rec: [");
  for (j = 0; ok && j < ci->field_count; j++)
    ok = (j == 0 || put(o, ", ")) && put(o, ci->fields[j].recursive ? "true" : "false");
  return ok && put(o, "] },\n");
}

static int emit_tables(Js *o) {
  const Machine *m = o->m;
  uint32_t i;
  int ok = put(o, "const FAMILIES = [\n");
  for (i = 0; ok && i < m->family_count; i++) {
    const FamilyInfo *f = &m->families[i];
    ok = put(o, "  { name: ") && put_name(o, f->name) && put(o, ", first: ") && put_u64(o, f->first_ctor)
      && put(o, ", count: ") && put_u64(o, f->ctor_count) && put(o, ", enumeration: ")
      && put(o, all_constants(m, f) ? "true" : "false") && put(o, " },\n");
  }
  ok = ok && put(o, "];\nconst CTORS = [\n");
  for (i = 0; ok && i < m->ctor_count; i++)
    ok = emit_ctor_row(o, &m->ctors[i]);
  return ok && put(o, "];\n");
}

/* Each definition is computed when first used, as def_value does. */
static int emit_defs(Js *o) {
  uint32_t i;
  int ok = 1;
  for (i = 0; ok && i < o->m->def_count; i++) {
    const DefInfo *d = &o->m->defs[i];
    o->def = d->name;
    ok = put(o, "const g") && put_u64(o, i) && put(o, " = once(() => ")
      && (d->body == NULL ? put(o, "null") : emit(o, 0, d->body)) && put(o, ");\n");
  }
  return ok;
}

static int emit_instance(Js *o, uint32_t index, char *type_text) {
  const DefInfo *d = &o->m->defs[index];
  o->def = d->name;
  if (!value_print(o->m, NULL, 0, d->type, type_text, JS_TYPE_MAX))
    return internal(o, "an instance type that does not print");
  return put(o, "    Object.freeze({ name: ") && put_name(o, d->name) && put(o, ", type: ")
    && put_name(o, type_text) && put(o, ", value: g") && put_u64(o, index) && put(o, "() }),\n");
}

/* The instance document of the JSON target, its values computed in JS. */
static int emit_document(Js *o, char *type_text) {
  uint32_t i;
  int ok = put(o, "export const document = Object.freeze({\n  kind: 'document',\n  lang: ") && put_name(o, json_lang_name)
    && put(o, ",\n  instances: Object.freeze([\n");
  for (i = 0; ok && i < o->m->def_count; i++)
    ok = !json_is_instance(&o->m->defs[i]) || emit_instance(o, i, type_text);
  return ok && put(o, "  ]),\n});\n");
}

static int emit_entry(Js *o, uint32_t index, const Entry *e) {
  const DefInfo *d = &o->m->defs[index];
  uint32_t k;
  int ok;
  o->def = d->name;
  ok = put(o, "  [") && put_name(o, d->name) && put(o, ", entry(") && put_name(o, d->name) && put(o, ", '");
  for (k = 0; ok && k < e->param_count; k++)
    ok = put(o, e->param_flag[k] ? "F" : "N");
  return ok && put(o, "', '") && put(o, e->result_flag ? "F" : "N") && put(o, "', g") && put_u64(o, index) && put(o, ")],\n");
}

/* The definitions that `langc eval` runs with arguments (all of them, as
   eval_command searches the domain too). */
static int emit_entries(Js *o) {
  uint32_t i;
  int ok = put(o, "export const entries = Object.freeze(Object.fromEntries([\n");
  for (i = 0; ok && i < o->m->def_count; i++) {
    Entry e;
    memset(&e, 0, sizeof e);
    ok = !entry_of(o->m, o->m->defs[i].type, &e) || emit_entry(o, i, &e);
  }
  return ok && put(o, "]));\nexport { encode };\n");
}

static int comparable(Machine *m, const Value *t, uint32_t depth);

/* A field type is in the context of the family parameters, as in check.c. */
static int family_comparable(Machine *m, const Value *t, uint32_t depth) {
  const FamilyInfo *f = &m->families[t->inst];
  const Env *env = NULL;
  uint32_t i;
  uint32_t j;
  int ok = 1;
  for (i = 0; i < f->param_count && i < t->argc; i++)
    env = env_push(m, env, t->args[i]);
  for (i = 0; ok && i < f->ctor_count; i++) {
    const CtorInfo *ci = &m->ctors[f->first_ctor + i];
    for (j = 0; ok && j < ci->field_count; j++)
      ok = ci->fields[j].recursive || comparable(m, eval_core(m, env, ci->fields[j].type), depth + 1u);
  }
  return ok;
}

static int op_comparable(Machine *m, const Value *t, uint32_t depth) {
  switch (t->op) {
  case OP_NAT:
  case OP_FLAG:
  case OP_STR:
  case OP_UNIT:
  case OP_EQ:
    return 1;
  case OP_PROD:
  case OP_SUM:
    return t->argc == 2 && comparable(m, t->args[0], depth + 1u) && comparable(m, t->args[1], depth + 1u);
  case OP_OPTION:
  case OP_LIST:
    return t->argc == 1 && comparable(m, t->args[0], depth + 1u);
  case OP_FAMILY:
    return t->inst < m->family_count && family_comparable(m, t, depth);
  case OP_UNIT_VAL:
  case OP_FLAG_YES:
  case OP_FLAG_NO:
  case OP_PAIR:
  case OP_INL:
  case OP_INR:
  case OP_NONE:
  case OP_SOME:
  case OP_NIL:
  case OP_CONS:
  case OP_PACK:
  case OP_REFL:
  case OP_CTOR:
  case OP_FIRST:
  case OP_SECOND:
  case OP_EITHER:
  case OP_OPTION_ELIM:
  case OP_PURE:
  case OP_MAP:
  case OP_BIND:
  case OP_FOLD_NAT:
  case OP_FOLD_LIST:
  case OP_FOLD_FAMILY:
  case OP_UNFOLD:
  case OP_FILTER:
  case OP_WITNESS:
  case OP_PAYLOAD:
  case OP_SYMM:
  case OP_TRANS:
  case OP_TRANSPORT:
  case OP_CONG:
  case OP_NAT_ADD:
  case OP_NAT_SUB:
  case OP_NAT_MUL:
  case OP_NAT_EQ:
  case OP_NAT_LE:
  case OP_FLAG_IF:
  case OP_STR_EQ:
  case OP_SHOW_NAT:
  case OP_PROJ:
    return 0;
  }
  return 0;
}

/* 1 when the values of type T compare in JS as their normal forms compare in
   C: no function and no type inside. */
static int comparable(Machine *m, const Value *t, uint32_t depth) {
  if (t == NULL || depth >= JS_CARRIER_DEPTH)
    return 0;
  switch (t->kind) {
  case VAL_OP:
    return op_comparable(m, t, depth);
  case VAL_SIGMA:
    return comparable(m, t->dom, depth + 1u) && comparable(m, closure_apply(m, t, val_var(m, 0)), depth + 1u);
  case VAL_NAT:
  case VAL_STR:
  case VAL_TRAP:
  case VAL_UNIV:
  case VAL_LAM:
  case VAL_PI:
  case VAL_VAR:
  case VAL_APP:
  case VAL_STUCK:
    return 0;
  }
  return 0;
}

static int is_test(const DefInfo *d) {
  return d->type != NULL && val_is(d->type, OP_EQ) && d->type->argc == 3;
}

/* Both sides as written in the type (else their normal forms, for a type
   that is Eq only after evaluation). */
static int emit_test(Js *o, const DefInfo *d) {
  Machine *m = o->m;
  const Core *t = d->type_core;
  int direct = t != NULL && t->kind == CORE_OP && t->op == OP_EQ && t->argc == 3;
  const Core *left;
  const Core *right;
  o->def = d->name;
  m->def = d->name;
  m->fuel = EVAL_FUEL_STEPS;
  m->depth = 0;
  if (!comparable(m, d->type->args[0], 0))
    return put(o, "// selftest skips ") && put_name(o, d->name) && put(o, ": its carrier has a function or a type inside\n");
  left = direct ? t->args[1] : quote_value(m, 0, d->type->args[1]);
  right = direct ? t->args[2] : quote_value(m, 0, d->type->args[2]);
  return left != NULL && right != NULL && put(o, "check(") && put_name(o, d->name) && put(o, ", () => ")
    && emit(o, 0, left) && put(o, ", () => ") && emit(o, 0, right) && put(o, ");\n");
}

static int emit_selftest(Js *o) {
  uint32_t i;
  int ok = put(o, "// The selftest: both sides of each Eq-typed definition, evaluated here.\n");
  for (i = 0; ok && i < o->m->def_count; i++)
    ok = !is_test(&o->m->defs[i]) || emit_test(o, &o->m->defs[i]);
  return ok;
}

int js_module(Machine *m, int selftest, const char **text, size_t *len) {
  Js o;
  char *type_text = arena_alloc(m->arena, JS_TYPE_MAX);
  memset(&o, 0, sizeof o);
  o.m = m;
  if (type_text == NULL)
    return diag_fail(m->diag, "OOM", NULL, "the arena limit is reached");
  if (!emit_runtime(&o) || !emit_tables(&o) || !emit_defs(&o) || !emit_document(&o, type_text) || !emit_entries(&o))
    return 0;
  if (selftest && !emit_selftest(&o))
    return 0;
  *text = o.data;
  *len = o.len;
  return 1;
}
