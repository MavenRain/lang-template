typedef enum {
  JS_CONST, /* the name alone; the arguments are types or there are none */
  JS_CALL,  /* name(arguments) */
  JS_LEAD   /* name(number, arguments): the carrier, family, constructor or field */
} Shape;

typedef struct {
  Machine *m;
  const char *def; /* the current definition, for diagnostics */
  char *data;
  size_t len;
  size_t cap;
} Js;

static int put_n(Js *o, const char *s, size_t n) {
  if (o->len + n >= o->cap) {
    size_t cap = o->cap == 0 ? 4096u : o->cap;
    char *next;
    while (cap <= o->len + n)
      cap *= 2u;
    next = arena_alloc(o->m->arena, cap);
    if (next == NULL)
      return diag_fail(o->m->diag, "OOM", o->def, "the arena limit is reached");
    if (o->len > 0)
      memcpy(next, o->data, o->len);
    o->data = next;
    o->cap = cap;
  }
  memcpy(o->data + o->len, s, n);
  o->len += n;
  return 1;
}

static int put(Js *o, const char *s) {
  return put_n(o, s, strlen(s));
}

static int put_u64(Js *o, uint64_t n) {
  char num[24];
  snprintf(num, sizeof num, "%llu", (unsigned long long)n);
  return put(o, num);
}

static int internal(Js *o, const char *what) {
  return diag_fail(o->m->diag, "INTERNAL", o->def, "the JS writer found %s", what);
}

/* The byte count of the UTF-8 sequence that starts with C, or 0. */
static size_t utf8_width(unsigned c) {
  if (c < 0x80u)
    return 1;
  if (c >= 0xc2u && c <= 0xdfu)
    return 2;
  if (c >= 0xe0u && c <= 0xefu)
    return 3;
  return c >= 0xf0u && c <= 0xf4u ? 4 : 0;
}

/* The code point at S[*AT] in strict UTF-8 (no overlong form, no surrogate,
   at most U+10FFFF), or -1. Moves *AT past it. */
static long utf8_next(const unsigned char *s, size_t len, size_t *at) {
  static const unsigned long LEAST[5] = {0, 0, 0x80u, 0x800u, 0x10000u};
  size_t n = utf8_width(s[*at]);
  unsigned long cp;
  size_t i;
  if (n == 0 || *at + n > len)
    return -1;
  cp = n == 1 ? s[*at] : s[*at] & (0xffu >> (n + 1u));
  for (i = 1; i < n; i++) {
    if ((s[*at + i] & 0xc0u) != 0x80u)
      return -1;
    cp = cp << 6 | (s[*at + i] & 0x3fu);
  }
  if (cp < LEAST[n] || cp > 0x10ffffu || (cp >= 0xd800u && cp <= 0xdfffu))
    return -1;
  *at += n;
  return (long)cp;
}

static int put_unit(Js *o, unsigned long u) {
  char esc[8];
  snprintf(esc, sizeof esc, "\\u%04lx", u);
  return put(o, esc);
}

static int put_code_point(Js *o, unsigned long cp) {
  char c = (char)cp;
  if (cp >= 0x20u && cp < 0x7fu && cp != '\'' && cp != '\\')
    return put_n(o, &c, 1);
  if (cp <= 0xffffu)
    return put_unit(o, cp);
  return put_unit(o, 0xd800u + ((cp - 0x10000u) >> 10)) && put_unit(o, 0xdc00u + ((cp - 0x10000u) & 0x3ffu));
}

/* A JS string literal of the UTF-8 bytes S. A JS string holds code points,
   so bytes that are not UTF-8 are refused (strEq compares bytes in C and
   code units in JS; the two agree on UTF-8). */
static int put_js_string(Js *o, const char *s, size_t len) {
  const unsigned char *b = (const unsigned char *)s;
  size_t at = 0;
  int ok = put(o, "'");
  while (ok && at < len) {
    long cp = utf8_next(b, len, &at);
    if (cp < 0)
      return diag_fail(o->m->diag, "JS_UTF8", o->def, "a string holds bytes that are not UTF-8, which a JS string cannot hold");
    ok = put_code_point(o, (unsigned long)cp);
  }
  return ok && put(o, "'");
}

static int put_name(Js *o, const char *name) {
  return put_js_string(o, name, strlen(name));
}

