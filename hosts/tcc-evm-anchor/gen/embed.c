/* Writes the prelude as C (src/prelude.h), run by make with:
 *   tcc -std=c99 -Wall -Werror -run gen/embed.c domain/domain.lang build/domain.c
 * Exit 0 ok, 1 when IN is larger than EMBED_MAX bytes or OUT is not
 * written, 2 usage or a name that is not a plain path. */
#include "../src/prelude.h"
#include <stdio.h>
#include <string.h>

enum { EMBED_MAX = 1 << 20, EMBED_ROW = 12 };

static unsigned char bytes[EMBED_MAX + 1];

static int usage(void) {
  fputs("usage: tcc -run gen/embed.c IN OUT\n", stderr);
  return 2;
}

static int refuse(const char *what, const char *path) {
  fprintf(stderr, "embed: %s: %s\n", what, path);
  return 1;
}

int main(int argc, char **argv) {
  if (argc != 3)
    return usage();
  if (strpbrk(argv[1], "\"\\") != NULL)
    return usage();
  FILE *in = fopen(argv[1], "rb");
  if (in == NULL)
    return refuse("cannot read", argv[1]);
  size_t size = fread(bytes, 1, sizeof bytes, in);
  int broken = ferror(in);
  fclose(in);
  if (broken)
    return refuse("cannot read", argv[1]);
  if (size > EMBED_MAX)
    return refuse("larger than 1 MiB", argv[1]);
  FILE *out = fopen(argv[2], "wb");
  if (out == NULL)
    return refuse("cannot write", argv[2]);
  fprintf(out, "/* Generated by gen/embed.c from %s. Do not edit. */\n", argv[1]);
  fputs("#include \"../src/prelude.h\"\n\n", out);
  fprintf(out, "const char lang_prelude_name[] = \"%s\";\n", argv[1]);
  fprintf(out, "const size_t lang_prelude_size = %zu;\n", size);
  fputs("const unsigned char lang_prelude_text[] = {", out);
  for (size_t i = 0; i < size; i++)
    fprintf(out, "%s0x%02x,", i % EMBED_ROW == 0 ? "\n  " : " ", (unsigned)bytes[i]);
  fputs("\n  0x00\n};\n", out);
  int failed = ferror(out);
  failed |= fclose(out) != 0;
  return failed ? refuse("cannot write", argv[2]) : 0;
}
